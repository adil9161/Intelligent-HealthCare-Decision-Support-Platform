from pydantic import BaseModel, Field
from typing import List, Optional, Dict, Any

class TriageInput(BaseModel):
    patient_id: Optional[str] = None
    name: Optional[str] = "Anonymous Patient"
    age: int = Field(45, ge=0, le=120)
    gender: Optional[str] = "Other"
    symptoms: List[str] = Field(..., min_length=1)
    severity: float = Field(5.0, ge=1.0, le=10.0) # 1.0 (Mild) to 10.0 (Extremely Critical)
    urgency: str = Field("Urgent") # "Emergency", "Urgent", "Semi-Urgent", "Non-Urgent"
    vitals: Optional[Dict[str, Any]] = Field(default_factory=dict) # bp, heart_rate, spo2, temperature

class DepartmentCandidate(BaseModel):
    rank: int
    department: str
    department_code: str
    decision_score: float # 0.0 to 100.0%
    score: Optional[float] = None # Alias for decision_score
    certainty_factor: float # -1.0 to +1.0 (Unit 4 Buchanan-Shortliffe formula)
    fuzzy_severity_degree: float # 0.0 to 1.0
    fuzzy_urgency_degree: float # 0.0 to 1.0
    severity_compatibility: Optional[float] = None # 0.0 to 100.0%
    urgency_compatibility: Optional[float] = None # 0.0 to 100.0%
    is_red_flag_alert: bool
    matched_symptoms: List[str]
    matching_symptoms: Optional[List[str]] = None # Alias for matched_symptoms
    activated_rules: List[str]
    suggested_resource_tier: str
    clinical_rationale: str
    plain_language_explanation: Optional[str] = None # Human-readable explanation without jargon
    explanation: Optional[str] = None # Alias for plain_language_explanation
    floor: Optional[str] = None
    critical_resources: Optional[List[str]] = None

class TopResultResponse(BaseModel):
    department: str
    department_code: str
    score: float
    matching_symptoms: List[str]
    severity_compatibility: float
    urgency_compatibility: float
    plain_language_explanation: str
    certainty_factor: float

class TriageEvaluationResponse(BaseModel):
    patient_profile: Dict[str, Any]
    primary_recommendation: DepartmentCandidate
    top_result: Optional[TopResultResponse] = None
    ranked_alternatives: List[DepartmentCandidate]
    all_evaluated_departments: Optional[List[DepartmentCandidate]] = None
    rule_engine_trace: List[Dict[str, Any]]
    fuzzy_membership_breakdown: Dict[str, Any]
    certainty_factor_trace: Dict[str, Any]
    search_pathway: Optional[Dict[str, Any]] = None
    search_comparison: Optional[Dict[str, Any]] = None
    graceful_degradation_applied: Optional[bool] = False
    graceful_degradation_notice: Optional[str] = None
    minimax_exclusion_reasoning: Optional[Dict[str, Any]] = None
    warnings: Optional[List[str]] = None
    ethical_disclaimer: str = (
        "DECISION SUPPORT ADVISORY ONLY: This recommendation is generated by the "
        "AegisHealth AI Inference Engine as clinical guidance. Final triage, diagnostic, "
        "and therapeutic authority strictly remains with the licensed human attending physician."
    )
    timestamp: str

class SearchGraphRequest(BaseModel):
    start_node: str = "triage_intake"
    goal_department: Optional[str] = "Cardiology"
    algorithm: str = "ASTAR" # "BFS", "DFS", "GREEDY", "ASTAR"
    patient_severity: float = 8.5
    patient_urgency: str = "Emergency"
    symptoms: List[str] = Field(default_factory=lambda: ["Crushing Retrosternal Chest Pain", "Diaphoresis"])

class SearchStep(BaseModel):
    step_number: int
    current_node: str
    current_node_label: str
    frontier_queue: List[str]
    explored_set: List[str]
    g_cost: float
    h_cost: float
    f_cost: float
    decision_log: str

class SearchGraphResponse(BaseModel):
    algorithm: str
    start_node: str
    goal_node: str
    path_found: bool
    optimal_path: List[str]
    optimal_path_labels: List[str]
    total_path_cost: float
    nodes_expanded_count: int
    execution_trace: List[SearchStep]
    academic_notes: str
    execution_time_ms: Optional[float] = None
